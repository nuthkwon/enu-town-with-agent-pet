import { writeFileSync } from 'node:fs';
import { Canvas } from '../src/draw/canvas';
import { hex } from '../src/draw/color';
import { encodePng } from '../src/png';
import { renderAvatarFrame } from '../src/avatar';
import { HAIR_STYLES, HAIR_COLORS, OUTFIT_COLORS, SKIN_TONES } from '@enu/shared';
const frames: any[] = [['down','idle',0],['left','idle',0],['right','walk',0],['up','idle',0]];
const rows = HAIR_STYLES.map((h,i)=>({body: i%2? 'm':'f', hair:h, hairColor: HAIR_COLORS[i], outfit: OUTFIT_COLORS[i], skin: SKIN_TONES[i%3], wings: i===2||i===5}));
const c = new Canvas(frames.length*2*33, 4*33);
c.map(()=>hex('#f6eefa'));
rows.forEach((p:any,ri)=>frames.forEach(([d,a,i]:any,col:number)=>c.blit(renderAvatarFrame(p,d,a,i),((ri%2)*frames.length+col)*33,Math.floor(ri/2)*33)));
writeFileSync('/home/user/enu-preview/hairs.png', encodePng(c.scale(6)));
