import { writeFileSync } from 'node:fs';
import { PET_SPECIES } from '@enu/shared';
import { Canvas } from '../src/draw/canvas';
import { hex } from '../src/draw/color';
import { encodePng } from '../src/png';
import { renderPetFrame } from '../src/pet';
const frames: any[] = [['left','idle',0],['left','idle',1],['left','hop',0],['left','sleep',0],['right','idle',2]];
const c = new Canvas(frames.length*25, PET_SPECIES.length*25);
c.map(()=>hex('#f6eefa'));
PET_SPECIES.forEach((sp,row)=>frames.forEach(([d,a,i]:any,col:number)=>c.blit(renderPetFrame(sp,d,a,i),col*25,row*25)));
writeFileSync('/home/user/enu-preview/zoompet.png', encodePng(c.scale(6)));
