import { writeFileSync } from 'node:fs';
import { Canvas } from '../src/draw/canvas';
import { hex } from '../src/draw/color';
import { encodePng } from '../src/png';
import { renderEffectFrame } from '../src/effects';
const names = ['zzz', 'dots', 'clock', 'alarm'] as const;
const c = new Canvas(names.length * 18, 18);
c.map(() => hex('#f6eefa'));
names.forEach((n, i) => c.blit(renderEffectFrame(n), i * 18 + 1, 1));
writeFileSync('/home/user/enu-preview/fx.png', encodePng(c.scale(10)));
