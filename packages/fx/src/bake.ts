import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Canvas, encodePng } from '@enu/sprites';
import { stripFrames } from './check';
import { CATALOG_FILE, STRIPS_DIR, STRIPS_URL, denOf, effectIds, loadEffect } from './effects';
import { fxlib } from './pixelfx';
import type { FxCatalogEntry, LoadedFx } from './types';

/**
 * Bakes every effect (and each variant) into one horizontal strip PNG: frame i at x = i * w. Phaser plays it as a
 * spritesheet, CSS with `steps(frames)`. A one-shot's last frame (checked to be empty) is dropped. Output is
 * deterministic (seeded effects, the same PNG encoder as the other sprites), so CI can diff it.
 */

/** Per-strip and total byte budgets (tests and the bake enforce them). */
export const MAX_STRIP_BYTES = 48 * 1024;
export const MAX_TOTAL_BYTES = 900 * 1024;

export interface BakedStrip {
  key: string;
  file: string;
  png: Buffer;
  entry: FxCatalogEntry;
}

export function stripFileName(id: string, variant?: string): string {
  return `${id.replace('/', '-')}${variant ? `--${variant}` : ''}.png`;
}

/** Renders one effect (or one variant) to its strip. */
export function bakeStrip(fx: LoadedFx, variant?: string): BakedStrip {
  const den = denOf(fx);
  const options = variant ? den.variants[variant] : undefined;
  if (variant && !options) throw new Error(`${fx.id}: no variant ${variant}`);
  const r = fxlib.renderFrames(fx, { bg: 'none', options });
  const frames = stripFrames(fx.meta);
  const { w, h } = r;
  const strip = new Canvas(w * frames, h);
  for (let i = 0; i < frames; i++) {
    const src = r.frames[i]!.clear;
    for (let y = 0; y < h; y++) {
      const row = src.subarray(y * w * 4, (y + 1) * w * 4);
      strip.data.set(row, (y * strip.width + i * w) * 4);
    }
  }
  const png = encodePng(strip);
  const file = stripFileName(fx.id, variant);
  const hash = createHash('sha256').update(png).digest('hex').slice(0, 10);
  return {
    key: variant ? `${fx.id}--${variant}` : fx.id,
    file,
    png,
    entry: {
      url: `${STRIPS_URL}/${file}?v=${hash}`,
      w,
      h,
      frames,
      fps: fx.meta.fps,
      loop: fx.meta.loop,
      pivot: [fx.meta.origin[0], fx.meta.origin[1]],
      surface: den.surface,
      depth: den.depth,
      anchor: den.anchor,
      scale: den.scale,
    },
  };
}

export async function bakeAll(): Promise<BakedStrip[]> {
  const out: BakedStrip[] = [];
  for (const id of effectIds()) {
    const fx = await loadEffect(id);
    const variants = Object.keys(denOf(fx).variants);
    if (variants.length === 0) out.push(bakeStrip(fx));
    for (const v of variants) out.push(bakeStrip(fx, v));
  }
  return out;
}

export function catalogSource(strips: BakedStrip[]): string {
  const lines = strips.map((s) => {
    const e = s.entry;
    return (
      `  '${s.key}': { url: '${e.url}', w: ${e.w}, h: ${e.h}, frames: ${e.frames}, fps: ${e.fps}, ` +
      `loop: ${e.loop}, pivot: [${e.pivot[0]}, ${e.pivot[1]}], surface: '${e.surface}', depth: '${e.depth}', ` +
      `anchor: '${e.anchor}', scale: ${e.scale} },`
    );
  });
  return [
    '// GENERATED by `pnpm sprites:build` (packages/fx/src/bake.ts) from packages/fx/effects. Do not edit.',
    "import type { FxCatalogEntry } from './types';",
    '',
    'export const FX_CATALOG = {',
    ...lines,
    '} as const satisfies Record<string, FxCatalogEntry>;',
    '',
    'export type FxId = keyof typeof FX_CATALOG;',
    '',
  ].join('\n');
}

/** Writes the strips, deletes stale ones, writes `index.json` and `catalog.gen.ts`. Returns total bytes. */
export function writeBake(strips: BakedStrip[]): number {
  let total = 0;
  for (const s of strips) {
    if (s.png.length > MAX_STRIP_BYTES)
      throw new Error(`${s.key}: strip is ${s.png.length} bytes, budget ${MAX_STRIP_BYTES}`);
    total += s.png.length;
  }
  if (total > MAX_TOTAL_BYTES) throw new Error(`effects total ${total} bytes, budget ${MAX_TOTAL_BYTES}`);
  mkdirSync(STRIPS_DIR, { recursive: true });
  const keep = new Set(strips.map((s) => s.file));
  if (existsSync(STRIPS_DIR))
    for (const f of readdirSync(STRIPS_DIR))
      if (f.endsWith('.png') && !keep.has(f)) rmSync(join(STRIPS_DIR, f));
  for (const s of strips) writeFileSync(join(STRIPS_DIR, s.file), s.png);
  const index = Object.fromEntries(strips.map((s) => [s.key, { ...s.entry, bytes: s.png.length }]));
  writeFileSync(join(STRIPS_DIR, 'index.json'), `${JSON.stringify(index, null, 2)}\n`);
  writeFileSync(CATALOG_FILE, catalogSource(strips));
  return total;
}
